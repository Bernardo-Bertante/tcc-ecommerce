#!/usr/bin/env bash

set -euo pipefail

usage() {
  cat <<'EOF'
Usage:
  deploy-order-service-stack.sh --database-password PASSWORD [options]

Options:
  --stack-name NAME                 CloudFormation stack name. Default: order-service-benchmark.
  --image-tag TAG                   Docker/ECR tag for all three images. Default: current timestamp.
  --repository-prefix PREFIX        Optional ECR repository prefix.
  --profile PROFILE                 AWS CLI profile.
  --region REGION                   AWS region.
  --database-password PASSWORD      RDS master password. Can also use DATABASE_PASSWORD env.
  --database-username USER          Default: orderuser.
  --database-name NAME              Default: orderdb.
  --db-instance-class CLASS         Default: db.t3.micro.
  --db-engine-version VERSION       Default: 16.14.
  --task-execution-role-arn ARN     Optional existing IAM role ARN for ECS task execution.
  --task-role-arn ARN               Optional existing IAM role ARN for ECS task role.
  --task-cpu CPU                    Default: 1024.
  --task-memory MB                  Default: 3072.
  --desired-count COUNT             Default: 1.
  --max-task-count COUNT            Default: 5.
  --benchmark-ingress-cidr CIDR     CIDR allowed to reach ALB listeners. No unsafe default (provide operator IP/32).
  --skip-build                      Reuse local Docker images.
  --skip-push                       Reuse --image-uris-env values.
  --skip-gradle                     Forwarded to image preparation.
  --skip-native-build               Forwarded to image preparation.
  --image-uris-env PATH             Env file generated by push-order-service-images.sh.
  -h, --help                        Show this help.
EOF
}

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
AWS_DIR="$(cd -- "$SCRIPT_DIR/.." && pwd)"
TEMPLATE_FILE="$AWS_DIR/order-service-stack.yaml"
STACK_NAME="order-service-benchmark"
IMAGE_TAG="${IMAGE_TAG:-$(date +%Y%m%d-%H%M%S)}"
REPOSITORY_PREFIX="${REPOSITORY_PREFIX:-}"
PROFILE=""
REGION=""
DATABASE_PASSWORD="${DATABASE_PASSWORD:-}"
DATABASE_USERNAME="orderuser"
DATABASE_NAME="orderdb"
DB_INSTANCE_CLASS="db.t3.micro"
DB_ENGINE_VERSION="16.14"
TASK_EXECUTION_ROLE_ARN=""
TASK_ROLE_ARN=""
TASK_CPU="8192"
TASK_MEMORY="16384"
DESIRED_COUNT="1"
MAX_TASK_COUNT="5"
BENCHMARK_INGRESS_CIDR=""
SKIP_BUILD=false
SKIP_PUSH=false
SKIP_GRADLE=false
SKIP_NATIVE_BUILD=false
IMAGE_URIS_ENV="$AWS_DIR/build/order-service/image-uris.env"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --stack-name)
      STACK_NAME="$2"
      shift 2
      ;;
    --image-tag)
      IMAGE_TAG="$2"
      shift 2
      ;;
    --repository-prefix)
      REPOSITORY_PREFIX="$2"
      shift 2
      ;;
    --profile)
      PROFILE="$2"
      shift 2
      ;;
    --region)
      REGION="$2"
      shift 2
      ;;
    --database-password)
      DATABASE_PASSWORD="$2"
      shift 2
      ;;
    --database-username)
      DATABASE_USERNAME="$2"
      shift 2
      ;;
    --database-name)
      DATABASE_NAME="$2"
      shift 2
      ;;
    --db-instance-class)
      DB_INSTANCE_CLASS="$2"
      shift 2
      ;;
    --db-engine-version)
      DB_ENGINE_VERSION="$2"
      shift 2
      ;;
    --task-execution-role-arn)
      TASK_EXECUTION_ROLE_ARN="$2"
      shift 2
      ;;
    --task-role-arn)
      TASK_ROLE_ARN="$2"
      shift 2
      ;;
    --task-cpu)
      TASK_CPU="$2"
      shift 2
      ;;
    --task-memory)
      TASK_MEMORY="$2"
      shift 2
      ;;
    --desired-count)
      DESIRED_COUNT="$2"
      shift 2
      ;;
    --max-task-count)
      MAX_TASK_COUNT="$2"
      shift 2
      ;;
    --benchmark-ingress-cidr)
      BENCHMARK_INGRESS_CIDR="$2"
      shift 2
      ;;
    --skip-build)
      SKIP_BUILD=true
      shift
      ;;
    --skip-push)
      SKIP_PUSH=true
      shift
      ;;
    --skip-gradle)
      SKIP_GRADLE=true
      shift
      ;;
    --skip-native-build)
      SKIP_NATIVE_BUILD=true
      shift
      ;;
    --image-uris-env)
      IMAGE_URIS_ENV="$2"
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "Unknown argument: $1" >&2
      usage >&2
      exit 1
      ;;
  esac
done

if [[ -z "$DATABASE_PASSWORD" ]]; then
  echo "--database-password or DATABASE_PASSWORD is required." >&2
  usage >&2
  exit 1
fi
if ! command -v aws > /dev/null 2>&1; then
  echo "aws CLI is required." >&2
  exit 1
fi

PROFILE="${PROFILE:-${AWS_PROFILE:-pessoal}}"
REGION="${REGION:-${AWS_REGION:-us-east-1}}"

AWS_ARGS=(--profile "$PROFILE" --region "$REGION")

if [[ -z "$BENCHMARK_INGRESS_CIDR" ]]; then
  echo "ERROR: --benchmark-ingress-cidr is required and must not be 0.0.0.0/0. Use the operator IP in /32 form (see runbook)." >&2
  exit 1
fi

if [[ -n "$TASK_EXECUTION_ROLE_ARN" || -n "$TASK_ROLE_ARN" ]]; then
  echo "Using existing ECS roles (TaskExecutionRole/TaskRole) provided via ARN(s)."
  CFN_CAPABILITIES=()
else
  echo "Template will create ECS IAM roles. CAPABILITY_NAMED_IAM is required."
  CFN_CAPABILITIES=(--capabilities CAPABILITY_NAMED_IAM)
fi

account_id="$(aws "${AWS_ARGS[@]}" sts get-caller-identity --query Account --output text)"
echo "Deploy target: account=$account_id profile=$PROFILE region=$REGION"

if [[ "$SKIP_PUSH" == false ]]; then
  PUSH_ARGS=(--image-tag "$IMAGE_TAG" --output-env "$IMAGE_URIS_ENV")
  if [[ -n "$REPOSITORY_PREFIX" ]]; then
    PUSH_ARGS+=(--repository-prefix "$REPOSITORY_PREFIX")
  fi
  if [[ -n "$PROFILE" ]]; then
    PUSH_ARGS+=(--profile "$PROFILE")
  fi
  if [[ -n "$REGION" ]]; then
    PUSH_ARGS+=(--region "$REGION")
  fi
  if [[ "$SKIP_BUILD" == true ]]; then
    PUSH_ARGS+=(--skip-build)
  fi
  if [[ "$SKIP_GRADLE" == true ]]; then
    PUSH_ARGS+=(--skip-gradle)
  fi
  if [[ "$SKIP_NATIVE_BUILD" == true ]]; then
    PUSH_ARGS+=(--skip-native-build)
  fi

  "$SCRIPT_DIR/push-order-service-images.sh" "${PUSH_ARGS[@]}"
fi

if [[ ! -f "$IMAGE_URIS_ENV" ]]; then
  echo "Image URI env file was not found: $IMAGE_URIS_ENV" >&2
  exit 1
fi

set -a
# shellcheck source=/dev/null
source "$IMAGE_URIS_ENV"
set +a

required_image_vars=(SPRINGBOOT_IMAGE_URI QUARKUS_JVM_IMAGE_URI QUARKUS_NATIVE_IMAGE_URI)
for var_name in "${required_image_vars[@]}"; do
  if [[ -z "${!var_name:-}" ]]; then
    echo "Missing $var_name in $IMAGE_URIS_ENV" >&2
    exit 1
  fi
done

aws "${AWS_ARGS[@]}" cloudformation deploy \
  --stack-name "$STACK_NAME" \
  --template-file "$TEMPLATE_FILE" \
  "${CFN_CAPABILITIES[@]}" \
  --no-fail-on-empty-changeset \
  --parameter-overrides \
    ImageTag="$IMAGE_TAG" \
    SpringBootImageUri="$SPRINGBOOT_IMAGE_URI" \
    QuarkusJvmImageUri="$QUARKUS_JVM_IMAGE_URI" \
    QuarkusNativeImageUri="$QUARKUS_NATIVE_IMAGE_URI" \
    DatabaseName="$DATABASE_NAME" \
    DatabaseUsername="$DATABASE_USERNAME" \
    DatabasePassword="$DATABASE_PASSWORD" \
    DbInstanceClass="$DB_INSTANCE_CLASS" \
    DbEngineVersion="$DB_ENGINE_VERSION" \
    ExistingTaskExecutionRoleArn="$TASK_EXECUTION_ROLE_ARN" \
    ExistingTaskRoleArn="$TASK_ROLE_ARN" \
    TaskCpu="$TASK_CPU" \
    TaskMemory="$TASK_MEMORY" \
    DesiredCount="$DESIRED_COUNT" \
    MaxTaskCount="$MAX_TASK_COUNT" \
    BenchmarkIngressCidr="$BENCHMARK_INGRESS_CIDR"

aws "${AWS_ARGS[@]}" cloudformation describe-stacks \
  --stack-name "$STACK_NAME" \
  --query 'Stacks[0].Outputs[].[OutputKey,OutputValue]' \
  --output table